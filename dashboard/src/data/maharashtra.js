// Deterministic hash: spreads names across gat numbers so each gat gets a unique name
function nameForGat(gatNo) {
  const n = parseInt(gatNo, 10) || 0;
  // FNV-like mix so consecutive gat numbers get very different indices
  const h = ((n * 2654435761) ^ (n >> 5)) >>> 0;
  return MAHA_NAMES[h % MAHA_NAMES.length];
}

function pick(arr, idx) { return arr[idx % arr.length]; }

// Seeded pseudo-random: gives stable but scattered positions
function seededRand(seed) {
  const s = Math.sin(seed * 9301 + 49297) * 233280;
  return s - Math.floor(s);
}

// Maharashtra geographic bounds: lng 72.6–80.9, lat 15.6–22.0
function randLng(seed) { return 72.6 + seededRand(seed) * 8.3; }
function randLat(seed) { return 15.6 + seededRand(seed + 100) * 6.4; }
function parcelSize(seed) { return 0.008 + seededRand(seed + 200) * 0.025; }

